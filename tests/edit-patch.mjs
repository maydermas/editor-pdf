import { createRequire } from 'node:module';
import { spawn } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { PDFDocument, StandardFonts, setCharacterSpacing, setWordSpacing, pushGraphicsState, popGraphicsState } from 'pdf-lib';
const { chromium } = createRequire(import.meta.url)('playwright');
// Editar una palabra de una línea con espaciado especial: solo se redibuja esa palabra.
// Uso: npm run build && node tests/edit-patch.mjs
const S = (process.env.OUT_DIR || '/tmp/editor-pdf-patch') + '/';
(await import('node:fs')).mkdirSync(S, { recursive: true });
let fails = 0;
const check = (name, ok, detail = '') => { if (!ok) fails++; console.log(`${ok ? 'OK  ' : 'FALLO'} ${name}${detail ? ' — ' + detail : ''}`); };
const d = await PDFDocument.create();
const hel = await d.embedFont(StandardFonts.Helvetica); const helB = await d.embedFont(StandardFonts.HelveticaBold);
const p = d.addPage([595, 842]);
p.drawText('REUNIDOS', { x: 260, y: 740, size: 10, font: helB });
p.pushOperators(pushGraphicsState(), setWordSpacing(6));
p.drawText('De una parte,', { x: 70, y: 720, size: 10, font: hel });
p.pushOperators(setCharacterSpacing(1.2));
p.drawText('ANA MARIA COVACIU', { x: 140, y: 720, size: 11, font: hel });
p.pushOperators(setCharacterSpacing(0));
p.drawText('con N.I.E nº Y9092530T', { x: 290, y: 720, size: 10, font: hel });
p.pushOperators(popGraphicsState());
p.drawText('mayor de edad, vecina de ROQUETAS DE MAR', { x: 70, y: 707, size: 10, font: hel });
writeFileSync(S + 'contrato.pdf', await d.save());
const server = spawn(process.execPath, ['node_modules/vite/bin/vite.js','preview','--port','4801','--strictPort'],{stdio:'pipe'});
await new Promise(r=>server.stdout.on('data',x=>String(x).includes('4801')&&r()));
const b = await chromium.launch();
const t = await b.newContext({ viewport: { width: 1000, height: 700 }, deviceScaleFactor: 2 });
const pg = await t.newPage();
await pg.goto('http://localhost:4801/');
await pg.setInputFiles('[data-testid="file-input"]', S + 'contrato.pdf');
await pg.waitForSelector('.viewer .text-run'); await pg.waitForTimeout(1200);
const ov = await pg.locator('.page-overlay').first().boundingBox();
const clip = { x: ov.x + 50*ov.width/595, y: ov.y + 90*ov.height/842, width: 420*ov.width/595, height: 50*ov.height/842 };
await pg.screenshot({ path: S + 'k0.png', clip });
const run = pg.locator('.viewer .text-run[aria-label*="N.I.E"]').first();
await run.click(); await pg.waitForSelector('.text-editor');
const val = await pg.locator('.text-editor').inputValue();
await pg.locator('.text-editor').fill(val.replace('N.I.E', 'NIE'));
await pg.mouse.click(ov.x + 300, ov.y + 600); await pg.waitForTimeout(500);
const patch = await pg.locator('.viewer .ann-text').allTextContents();
check('solo se redibuja la palabra cambiada', patch.length === 1 && patch[0] === 'NIE', JSON.stringify(patch));
await pg.screenshot({ path: S + 'k1.png', clip });
// re-edit same line, change nothing more, then change last word
await pg.locator('.viewer .text-run[aria-label*="N.I.E"]').first().click().catch(e=>console.log('no run', e.message));
await pg.waitForTimeout(300);
check('al volver a abrir la línea se ve entera con el cambio', (await pg.locator('.text-editor').inputValue().catch(() => '')) === 'con NIE nº Y9092530T');
await pg.mouse.click(ov.x + 300, ov.y + 600); await pg.waitForTimeout(500);
await pg.screenshot({ path: S + 'k2.png', clip });
check('cerrarla sin más cambios deja el mismo parche', JSON.stringify(await pg.locator('.viewer .ann-text').allTextContents()) === '["NIE"]');
await b.close(); server.kill();
console.log(fails ? `${fails} fallos` : 'Todo correcto');
process.exit(fails ? 1 : 0);
